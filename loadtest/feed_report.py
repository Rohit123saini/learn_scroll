"""
loadtest/feed_report.py - H2: turn the load-test artefacts into the four feed numbers and write them into README.md.

    python loadtest/feed_report.py [--out loadtest/out] [--csv-prefix run1k] [--no-readme]

Inputs (all in --out):
    <prefix>_stats.csv     Locust (`--csv loadtest/out/run1k`)          -> page-1 p95, page-2 p95, failures
    feed_stats.json        `manage.py feed_stats --json --out ...`      -> DB queries/page, Redis hit-rate
    explain_summary.json   `manage.py feed_explain_analyze ...`         -> slowest statements (optional)

Output: <out>/feed_h2_results.json, <out>/feed_h2_results.md, and the table between the
<!-- H2:START --> / <!-- H2:END --> markers of loadtest/README.md.
A number whose input file is missing is written as "NOT MEASURED" - nothing is ever estimated or defaulted.
Stdlib only (no Django needed), so it can run on the injector box.
"""
import argparse
import csv
import json
from datetime import date
from pathlib import Path

PAGE1 = "GET /post/feed/"
PAGE2 = "GET /post/feed/ [page 2]"
PAGE3 = "GET /post/feed/ [page 3+]"
TARGET_MS = 800  # locustfile.py THRESHOLDS
NM = "NOT MEASURED"


def read_locust(path: Path) -> dict:
    out = {}
    if not path.exists():
        return out
    with path.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            out[row["Name"]] = {
                "requests": int(row["Request Count"]), "failures": int(row["Failure Count"]),
                "p50_ms": float(row["50%"]), "p95_ms": float(row["95%"]), "p99_ms": float(row["99%"]),
            }
    return out


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def pct(rate):
    return NM if rate is None else f"{rate * 100:.1f} %"


def build(out_dir: Path, prefix: str) -> dict:
    loc = read_locust(out_dir / f"{prefix}_stats.csv")
    fs = read_json(out_dir / "feed_stats.json")
    ex = read_json(out_dir / "explain_summary.json")

    def p95(name):
        e = loc.get(name)
        return None if not e or e["requests"] == 0 else e["p95_ms"]

    res = {
        "date": date.today().isoformat(),
        "page1_p95_ms": p95(PAGE1), "page2_p95_ms": p95(PAGE2), "page3plus_p95_ms": p95(PAGE3),
        "samples": {k: loc[k]["requests"] for k in (PAGE1, PAGE2, PAGE3) if k in loc},
        "failures": {k: loc[k]["failures"] for k in (PAGE1, PAGE2, PAGE3) if k in loc},
        "db_queries_per_page": None, "queries_by_kind": {}, "feed_cache_hit_rate": None, "redis_server_hit_rate": None,
        "caches": {}, "slowest_statements": [],
    }
    if fs:
        res["db_queries_per_page"] = fs.get("avg_queries_all_pages")
        res["queries_by_kind"] = {k: v["avg_queries"] for k, v in fs["queries_per_page"].items() if v["requests"]}
        res["feed_cache_hit_rate"] = fs.get("feed_cache_hit_rate")
        res["caches"] = {k: v["hit_rate"] for k, v in fs["caches"].items()}
        res["redis_server_hit_rate"] = (fs.get("redis_server_wide") or {}).get("hit_rate")
    if ex:
        top = sorted((s for s in ex["statements"] if s.get("execution_ms") is not None),
                     key=lambda s: s["execution_ms"], reverse=True)[:5]
        res["slowest_statements"] = [{"group": s["group"], "execution_ms": s["execution_ms"],
                                      "seq_scans": [x["table"] for x in s["seq_scans"]], "advice": s["advice"]} for s in top]
    return res


def ms(v):
    return NM if v is None else f"{v:.0f} ms"


def verdict(v):
    return "" if v is None else (" ✅" if v <= TARGET_MS else " ❌ (> %d ms)" % TARGET_MS)


def to_markdown(r: dict) -> str:
    kinds = ", ".join(f"{k} {v}" for k, v in r["queries_by_kind"].items()) or NM
    lines = [
        f"_Measured on staging, run date {r['date']}. Generated by `loadtest/feed_report.py` - do not edit by hand._",
        "",
        "| Metric | Result | Target |",
        "|---|---|---|",
        f"| Page-1 p95 (`GET /post/feed/`) | {ms(r['page1_p95_ms'])}{verdict(r['page1_p95_ms'])} | ≤ {TARGET_MS} ms |",
        f"| Page-2 p95 (cursor, snapshot) | {ms(r['page2_p95_ms'])}{verdict(r['page2_p95_ms'])} | ≤ {TARGET_MS} ms |",
        f"| DB queries / page (avg, all pages) | {NM if r['db_queries_per_page'] is None else r['db_queries_per_page']} ({kinds}) | within `tests_feed_query_budget.py` |",
        f"| Redis hit-rate (feed caches: candidate + snapshot) | {pct(r['feed_cache_hit_rate'])} "
        f"(candidate {pct(r['caches'].get('cand'))}, snapshot {pct(r['caches'].get('snap'))}) | high; snapshot misses force a pool rebuild |",
        f"| Redis hit-rate (server-wide keyspace, secondary) | {pct(r['redis_server_hit_rate'])} | - |",
        "",
        f"Samples: {r['samples'] or NM}; failures: {r['failures'] or NM}.",
    ]
    if r["slowest_statements"]:
        lines += ["", "Slowest statements (`EXPLAIN ANALYZE`, full plans in `loadtest/out/explain_*.txt`):", ""]
        for s in r["slowest_statements"]:
            hint = f" - {'; '.join(s['advice'])}" if s["advice"] else ""
            lines.append(f"- `{s['group']}` {s['execution_ms']} ms, seq scans: {s['seq_scans'] or 'none'}{hint}")
    return "\n".join(lines) + "\n"


def inject(readme: Path, block: str) -> bool:
    start, end = "<!-- H2:START -->", "<!-- H2:END -->"
    text = readme.read_text(encoding="utf-8")
    if start not in text or end not in text:
        return False
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    readme.write_text(f"{head}{start}\n{block}{end}{tail}", encoding="utf-8")
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="loadtest/out")
    ap.add_argument("--csv-prefix", default="run1k")
    ap.add_argument("--readme", default="loadtest/README.md")
    ap.add_argument("--no-readme", action="store_true")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    res = build(out, a.csv_prefix)
    md = to_markdown(res)
    (out / "feed_h2_results.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    (out / "feed_h2_results.md").write_text(md, encoding="utf-8")
    print(md)
    if not a.no_readme:
        print("README updated." if inject(Path(a.readme), md) else f"{a.readme}: H2 markers not found - table not inserted.")
    missing = [k for k in ("page1_p95_ms", "page2_p95_ms", "db_queries_per_page", "feed_cache_hit_rate") if res[k] is None]
    if missing:
        print(f"INCOMPLETE - not measured: {', '.join(missing)}")
        raise SystemExit(2)


if __name__ == "__main__":
    main()
